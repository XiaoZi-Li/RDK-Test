# import 是Python导入模块的关键字，就像打开工具箱拿出需要的工具一样

# sys 是系统相关的模块，这里我们用它来处理程序退出
import sys

# signal 是信号处理模块，让我们能够捕获Ctrl+C来优雅地退出程序
import signal

# Hobot.GPIO 是地平线开发板提供的GPIO控制库，就像控制灯光的开关面板
# 注意：如果是RDK X5平台，这个库可能叫 Hobot.GPIO
#       如果导入失败，可能需要检查是否正确安装了开发环境
import Hobot.GPIO as GPIO

# time 是时间控制模块，让我们能够使用 sleep() 函数来延时
import time

# ***************************************************************************************************
# 第二部分：信号处理函数
# ***************************************************************************************************

# 为什么要信号处理？
# 当用户按Ctrl+C时，计算机会发送一个信号给程序
# 如果我们不处理这个信号，程序会突然中断，可能导致GPIO状态异常
# 所以我们需要捕获这个信号，做一些清理工作再退出

def signal_handler(signal, frame):
    """
    信号处理函数 - 当收到Ctrl+C时会被调用

    参数说明:
    - signal: 信号类型，Ctrl+C对应的是 SIGINT
    - frame: 当时的栈帧信息（我们用不到，但必须有这个参数）

    这个函数的执行流程:
    1. 用户按Ctrl+C
    2. Python调用这个signal_handler函数
    3. 函数执行 sys.exit(0)，程序正常退出
    """
    # sys.exit(0) 表示程序正常退出
    # 如果传入非0数字（如1），表示程序异常退出
    sys.exit(0)

# ***************************************************************************************************
# 第三部分：配置GPIO引脚
# ***************************************************************************************************

# 定义我们要控制的GPIO引脚
# 这里使用BOARD编码方式的37号引脚
# 重要概念解释：
#   - BOARD编码: 使用开发板上标注的物理引脚编号（1-40）
#   - BCM编码:   使用Broadcom芯片定义的编号（0-53）
#   - 新手建议用BOARD编码，因为开发板上的丝印就是BOARD编号
output_pin = 37  # GPIO 37号引脚（BOARD编码）

# GPIO.setwarnings(False) 的作用：
# 当GPIO引脚已经被其他程序使用时，Python会显示警告
# 我们把它关闭，避免干扰初学者
GPIO.setwarnings(False)

# ***************************************************************************************************
# 第四部分：主函数
# ***************************************************************************************************

def main():
    """
    主函数 - 程序的入口点

    函数的执行流程：
    1. 设置GPIO模式为BOARD
    2. 配置37号引脚为输出模式，并初始为高电平
    3. 进入无限循环，LED不断闪烁
    4. 当用户按Ctrl+C时，跳出循环并清理GPIO

    什么是"无限循环"？
    while True 就是无限循环，条件永远是True，所以永远不会自动停止
    必须通过 break 语句或者 sys.exit() 来退出
    """

    # -------------------- 步骤1：设置GPIO编码模式 --------------------
    # GPIO.setmode() 有两个常用模式：
    #   - GPIO.BOARD : 使用物理引脚编号（开发板上的1-40号）
    #   - GPIO.BCM   : 使用芯片定义的编号（需要查手册）
    #
    # 推荐新手使用 BOARD 模式，因为开发板上的丝印就是物理编号
    GPIO.setmode(GPIO.BOARD)

    # -------------------- 步骤2：配置引脚模式和初始电平 --------------------
    # GPIO.setup() 用于设置引脚的方向
    # 参数说明：
    #   - 第一个参数：引脚编号
    #   - 第二个参数：引脚方向，GPIO.OUT 表示输出，GPIO.IN 表示输入
    #   - initial   ：初始电平，GPIO.HIGH=高电平(3.3V)，GPIO.LOW=低电平(0V)
    #
    # 重要概念 - 什么是高电平和低电平？
    #   - 高电平(HIGH): 3.3V左右，可以点亮LED
    #   - 低电平(LOW):  0V左右，LED熄灭
    #
    # 小提示：为什么要设置初始电平？
    # 因为如果不确定初始状态，可能会导致LED一开始随机闪烁
    GPIO.setup(output_pin, GPIO.OUT, initial=GPIO.HIGH)

    # -------------------- 步骤3：记录当前引脚状态 --------------------
    # curr_value 变量用于记住当前LED的状态
    # 初始为 GPIO.HIGH，表示LED当前是亮的
    curr_value = GPIO.HIGH

    # -------------------- 步骤4：打印欢迎信息 --------------------
    print("Starting demo now! Press CTRL+C to exit")
    # 说明：
    #   - print() 是打印函数，把内容显示到终端
    #   - \n 在字符串末尾？不需要，因为print自动换行

    # -------------------- 步骤5：进入LED闪烁循环 --------------------
    try:
        """
        try...finally 结构的作用：
        try:   尝试执行这里的代码
        finally: 不管try里是否出错，都会执行这里的清理代码

        为什么要这样？
        因为即使程序出错，我们也希望执行 GPIO.cleanup()
        否则GPIO可能保持最后的状态，导致下次使用出问题
        """
        while True:
            # -------- while循环内：LED闪烁的核心逻辑 --------

            # time.sleep(1) - 暂停1秒钟
            # 参数单位是"秒"，可以是小数
            # 例如：0.5 = 500毫秒，0.001 = 1毫秒
            time.sleep(1)

            # GPIO.output() - 设置引脚输出电平
            # 第一个参数：引脚编号
            # 第二个参数：电平值，GPIO.HIGH 或 GPIO.LOW
            #
            # curr_value 的值是什么，就输出什么电平
            GPIO.output(output_pin, curr_value)

            # curr_value ^= GPIO.HIGH
            # 这是Python的复合赋值运算符
            # ^= 表示"异或后赋值"
            # GPIO.HIGH = 1（通常）
            # 所以 curr_value ^= 1 会让值在 0 和 1 之间切换
            # 相当于: curr_value = curr_value ^ GPIO.HIGH
            #
            # 简单理解：翻转 curr_value 的值
            # 如果是 1 变成 0，如果是 0 变成 1
            curr_value ^= GPIO.HIGH

            # 循环回到 while True，每次都会：
            # 1. 等1秒
            # 2. 输出当前电平
            # 3. 翻转电平状态

    finally:
        # 不管程序怎么结束的，都执行清理
        # 这是保证GPIO资源被正确释放的重要步骤
        GPIO.cleanup()
        # GPIO.cleanup() 的作用：
        #   - 释放所有已使用的GPIO引脚
        #   - 将所有引脚恢复为默认状态
        #   - 非常重要！不调用可能导致下次使用异常

# ***************************************************************************************************
# 第五部分：程序入口
# ***************************************************************************************************

# 这段代码是Python程序的固定写法
# 理解：
#   - __name__ 是Python的一个内置变量
#   - 当直接运行这个文件时，__name__ == '__main__' 为 True
#   - 当被其他文件导入时，这个条件不成立
#
# 为什么要这样写？
#   - 让我们能同时把代码当作"程序"运行和当作"模块"导入
#   - 这是Python的良好实践
if __name__ == '__main__':
    """
    程序入口点

    执行流程：
    1. 注册信号处理器（捕获Ctrl+C）
    2. 调用 main() 函数
    """

    # signal.signal() 用于注册信号处理函数
    # 第一个参数：我们要捕获的信号（SIGINT = Ctrl+C）
    # 第二个参数：收到信号后调用的函数
    signal.signal(signal.SIGINT, signal_handler)

    # 调用主函数，开始执行LED闪烁程序
    main()

