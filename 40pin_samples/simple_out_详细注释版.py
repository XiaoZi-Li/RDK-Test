# A: 简单理解：
#    高电平 = 通电状态 = LED亮
#    低电平 = 断电状态 = LED灭
#    就像开关的"开"和"关"
#
# ***************************************************************************************************
# 技术解释
# ***************************************************************************************************
#
# 1. 什么是GPIO？
#    GPIO = General Purpose Input/Output（通用输入输出）
#    就是可以由程序控制输出高低电平，或者读取当前电平状态的引脚
#
# 2. 什么是电平？
#    电平就是电压的高低
#    高电平通常约等于3.3V（开发板电压）
#    低电平约等于0V（地线）
#
# 3. 为什么要用电阻？
#    LED工作需要一定电流，约20mA
#    如果不加电阻，电流过大，可能烧坏LED或开发板
#    330Ω电阻可以把电流限制在安全范围
#
# 4. 什么是编码模式？
#    BOARD模式：用物理引脚编号（看开发板丝印）
#    BCM模式：  用芯片内部编号（需要查芯片手册）
#    就像一个楼房的房间编号，
#    BOARD模式 = 实际门牌号（301室）
#    BCM模式   = 建筑内部分配号（A-1-3）
#
