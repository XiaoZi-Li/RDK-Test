# 1. PWM的频率选择
#
#    ┌─────────────────────────────────────────────────────┐
#    │  应用场景          │  常用频率    │  说明           │
#    ├─────────────────────────────────────────────────────┤
#    │  LED调光           │  1-10kHz    │  人眼感觉不到闪烁 │
#    │  舵机控制          │  50Hz       │  标准舵机频率    │
#    │  直流电机调速      │  10-25kHz   │  电机无声       │
#    │  风扇调速          │  20kHz以上  │  避免噪音       │
#    └─────────────────────────────────────────────────────┘
#
# 2. 为什么LED需要PWM调光而不是直接调电压？
#
#    LED的特性：
#    - LED亮度与电流近似成正比
#    - LED需要恒流驱动
#    - 直接调电压可能导致亮度不稳定
#
#    PWM调光的优点：
#    - 电流恒定，亮度稳定
#    - 开关频率高，人眼无法分辨
#    - 能耗效率高（高电平时全功率，低电平时几乎不耗电）
#
# 3. 占空比与亮度感知的非线性关系
#
#    人眼对亮度的感知是对数的，不是线性的
#    这意味着：
#    - 10%到20%的亮度变化比80%到90%更明显
#    - 如果想让变化看起来更均匀
#    - 可以用指数曲线代替线性增加
#
#    例如：
#    for i in range(100):
#        # 线性
#        duty = i
#
#        # 对数（更均匀的呼吸效果）
#        duty = int(100 * (i/50) ** 2)  # 平方关系
#
# ***************************************************************************************************
# 常见问题
# ***************************************************************************************************
#
# Q: LED完全不亮？
# A: 检查：
#    1. 引脚是否正确？（32或33才支持PWM）
#    2. 接线是否正确？
#    3. 尝试增大初始占空比，如 val = 50
#
# Q: LED闪烁明显？
# A: 原因：
#    1. PWM频率太低
#    2. 尝试增大频率到10kHz以上
#    p = GPIO.PWM(output_pin, 10000)
#
