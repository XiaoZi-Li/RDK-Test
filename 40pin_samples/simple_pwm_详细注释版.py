# ***************************************************************************************************
# 第一部分：导入必要的库
# ***************************************************************************************************

import sys        # 系统相关，用于处理程序退出
import signal     # 信号处理，用于捕获Ctrl+C
import Hobot.GPIO as GPIO  # GPIO控制库
import time       # 时间控制，用于延时

# ***************************************************************************************************
# 第二部分：信号处理（与simple_out.py相同）
# ***************************************************************************************************

def signal_handler(signal, frame):
    """
    信号处理函数 - 当收到Ctrl+C时优雅退出

    为什么需要这个？
    如果用户突然按Ctrl+C强行退出程序
    PWM可能还在运行，LED可能一直亮着
    所以我们要捕获信号，做清理工作
    """
    sys.exit(0)

# ***************************************************************************************************
# 第三部分：PWM引脚配置
# ***************************************************************************************************

# 定义PWM输出的引脚
# 重要提示：不是所有引脚都支持PWM！
# 在RDK X3/X5上，通常只有32和33号引脚支持PWM
# 如果选错引脚，程序可能不会正常工作
output_pin = 33

# 禁用GPIO警告
# 当引脚被占用时，Python会显示警告
# 新手阶段我们先关闭它，避免干扰
GPIO.setwarnings(False)

# ***************************************************************************************************
# 第四部分：主函数
# ***************************************************************************************************

def main():
    """
    主函数 - 实现呼吸灯效果

    呼吸灯原理：
    1. 占空比从0%逐渐增加到100%
    2. 然后从100%逐渐减少到0%
    3. 不断循环

    什么是占空比（Duty Cycle）？
    ┌─────────────────────────────────────────────┐
    │  占空比 = 高电平时间 / 周期时间 × 100%        │
    │                                              │
    │  例如：                                      │
    │  周期 = 1秒                                  │
    │  高电平时间 = 0.5秒                           │
    │  占空比 = 0.5 / 1 × 100% = 50%              │
    │                                              │
    │  ═══════════════════════════════════        │
    │  高电平 ──────低电平──────                   │
    │  ═══════════════════════════════════        │
    │  0%       50%       100%                      │
    │                                              │
    │  50%占空比意味着LED有一半时间亮，一半时间灭     │
    │  人眼无法分辨这么快的闪烁，看到的就是中等亮度    │
    └─────────────────────────────────────────────┘
    """

    # -------------------- 步骤1：设置GPIO模式 --------------------
    # BOARD编码方式，使用物理引脚编号
    GPIO.setmode(GPIO.BOARD)

    # -------------------- 步骤2：创建PWM对象 --------------------
    # GPIO.PWM(引脚, 频率) 创建PWM对象
    #
    # 参数说明：
    # - 第一个：引脚号，这里是33号
    # - 第二个：PWM频率，单位是Hz（赫兹）
    #
    # 频率选择的艺术：
    # - 频率太高（如1MHz）：开关太快，电路可能反应不过来
    # - 频率太低（如1Hz）：人能明显看到闪烁
    # - 常用范围：50Hz（舵机）到20kHz（人耳听不到，用于电机）
    # - 对于LED调光：1kHz左右就很平滑
    #
    # 我们这里用48kHz（48000Hz），是非常高的频率
    # 人眼完全无法分辨，看到的就是连续的亮度变化
    p = GPIO.PWM(output_pin, 48000)

    # -------------------- 步骤3：设置初始占空比 --------------------
    #
    # 占空比初值：25%
    # 这意味着LED有25%的时间亮，75%的时间灭
    # 人眼看到的就是比较暗的亮度
    #
    # val 变量：当前占空比（百分比）
    val = 25

    # incr 变量：每次变化的增量
    # 每0.25秒，占空比增加5%
    incr = 5

    # -------------------- 步骤4：启动PWM --------------------
    #
    # p.start(初值) 启动PWM输出
    # 从指定的占空比开始输出PWM波形
    #
    # 小提示：start() 相当于打开开关
    # 之后可以用 ChangeDutyCycle() 随时改变亮度
    p.start(val)

    # -------------------- 步骤5：打印欢迎信息 --------------------
    print("PWM running. Press CTRL+C to exit.")
    print("LED会呈现呼吸灯效果：亮度从暗到亮，再从亮到暗...")

    # -------------------- 步骤6：呼吸灯主循环 --------------------
    try:
        while True:
            # -------- 每个循环执行一次 --------

            # time.sleep(0.25) - 每0.25秒变化一次
            # 这个值越小，亮度变化越平滑
            # 但太小的话，CPU占用会增高
            time.sleep(0.25)

            # -------- 到达100%时开始减少 --------
            # 当占空比达到或超过100时
            # 我们要让增量变为负值（减少）
            if val >= 100:
                incr = -incr  # 变成-5，开始减少

            # -------- 到达0%时开始增加 --------
            # 当占空比达到或低于0时
            # 我们要让增量变为正值（增加）
            if val <= 0:
                incr = -incr  # 变成+5，开始增加

            # -------- 更新当前占空比 --------
            # 每次循环，占空比增加或减少5%
            val += incr

            # -------- 应用新的占空比 --------
            # ChangeDutyCycle() 改变PWM的占空比
            # 这个函数不会停止PWM，只是改变亮度
            p.ChangeDutyCycle(val)

            # -------- 循环说明 --------
            # 假设从25%开始：
            # 0.25秒后 -> 30% -> 变亮一点
            # 0.25秒后 -> 35% -> 继续变亮
            # ... 不断增加直到100%
            # 然后开始减少：95%, 90%, 85%...
            # 直到0%，再开始增加
            # 不断循环，形成呼吸效果

    finally:
        # -------- 清理工作 --------
        # 不管怎么退出，都要停止PWM
        p.stop()  # 停止PWM输出
        GPIO.cleanup()  # 释放GPIO资源

# ***************************************************************************************************
# 第五部分：程序入口
# ***************************************************************************************************

if __name__ == '__main__':
    # 注册Ctrl+C信号处理
    signal.signal(signal.SIGINT, signal_handler)

    # 运行主程序
    main()

