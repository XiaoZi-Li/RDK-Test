def parse_arguments():
    """
    parse_arguments - 解析命令行参数

    这个程序支持以下用法：
    python test_all_pins.py           # 测试所有引脚
    python test_all_pins.py 15 16 37 # 测试指定引脚
    python test_all_pins.py -l        # 只列出引脚，不测试
    python test_all_pins.py -h        # 显示帮助
    """

    global running

    # sys.argv 是命令行参数列表
    # argv[0] = 程序名
    # argv[1], argv[2], ... = 用户输入的参数

    if len(sys.argv) == 1:
        # 没有参数，测试所有引脚
        print("使用默认设置：测试所有引脚")
        return ALL_GPIO_PINS

    elif len(sys.argv) == 2:
        # 有一个参数
        arg = sys.argv[1]

        if arg == "-l" or arg == "--list":
            # 列出引脚
            list_available_pins()
            return []

        elif arg == "-h" or arg == "--help":
            # 显示帮助
            print_help()
            return []

        elif arg == "-d" or arg == "--delay":
            print_help()
            return []

        else:
            # 可能是引脚号
            try:
                pins = [int(p) for p in sys.argv[1:]]
                print(f"测试指定引脚: {pins}")
                return pins
            except ValueError:
                print(f"错误：无法解析参数 '{arg}'")
                print_help()
                return []

    else:
        # 多个参数，都是引脚号
        try:
            pins = [int(p) for p in sys.argv[1:]]
            print(f"测试指定引脚: {pins}")
            return pins
        except ValueError as e:
            print(f"错误：参数包含无效的引脚号: {e}")
            print_help()
            return []

