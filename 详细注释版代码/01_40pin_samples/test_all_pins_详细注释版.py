def test_pin(pin, delay=0.25):
    """
    test_pin - 测试单个GPIO引脚

    参数:
        pin: 要测试的引脚号
        delay: 每个状态持续时间（秒）

    测试流程：
    1. 配置引脚为输出
    2. 输出HIGH电平（LED亮），延时
    3. 输出LOW电平（LED灭），延时
    4. 清理引脚
    """

    print(f"\n{'='*60}")
    print(f"测试引脚: GPIO {pin} (BOARD)")
    print(f"{'='*60}")
    print("提示: 按 Ctrl+C 跳到下一个引脚")
    print(f"每个状态持续: {delay}秒")
    print(f"{'='*60}\n")

    try:
        # -------------------- 配置引脚 --------------------
        # 设置为输出模式
        GPIO.setup(pin, GPIO.OUT)

        # -------------------- 主循环 --------------------
        while running:
            # -------- 输出HIGH（LED亮）--------
            GPIO.output(pin, GPIO.HIGH)
            print(f"[GPIO {pin}] 输出: HIGH (3.3V) - LED亮")
            time.sleep(delay)

            # 检查是否要退出
            if not running:
                break

            # -------- 输出LOW（LED灭）--------
            GPIO.output(pin, GPIO.LOW)
            print(f"[GPIO {pin}] 输出: LOW (0V) - LED灭")
            time.sleep(delay)

    except KeyboardInterrupt:
        # Ctrl+C在这里被捕获，但不退出
        # 主循环会检测running标志
        pass

    finally:
        # -------- 清理 --------
        # 重置引脚状态
        GPIO.output(pin, GPIO.HIGH)  # 恢复为高电平
        print(f"\nGPIO {pin} 测试完成，已恢复默认状态")


def test_all_pins(pins, delay=0.25):
    """
    test_all_pins - 测试所有指定引脚

    参数:
        pins: 引脚号列表
        delay: 每个状态持续时间
    """

    print(f"\n{'#'*60}")
    print(f"# GPIO引脚测试程序")
    print(f"#{'#'*60}")
    print(f"# 将测试 {len(pins)} 个引脚")
    print(f"# 引脚列表: {pins}")
    print(f"#{'#'*60}\n")

    for i, pin in enumerate(pins):
        print(f"\n[进度: {i+1}/{len(pins)}]")

        # 测试当前引脚
        test_pin(pin, delay)

        # 检查是否继续
        if not running:
            break

    print(f"\n所有引脚测试完成!")


def list_available_pins():
    """
    list_available_pins - 列出所有可用引脚
    """
    print("\n" + "=" * 60)
