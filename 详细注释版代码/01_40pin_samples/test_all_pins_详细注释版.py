if __name__ == '__main__':
    main()

# ***************************************************************************************************
# 知识详解
# ***************************************************************************************************
#
# 1. sys.argv 命令行参数
#
#    sys.argv 是Python中获取命令行参数的常用方式
#    ┌─────────────────────────────────────────────┐
#    │                                             │
#    │  $ python test.py arg1 arg2 arg3          │
#    │                                             │
#    │  sys.argv = [                              │
#    │      'test.py',    # argv[0] = 程序名     │
#    │      'arg1',       # argv[1] = 第一个参数 │
#    │      'arg2',       # argv[2] = 第二个参数 │
#    │      'arg3'        # argv[3] = 第三个参数 │
#    │  ]                                         │
#    │                                             │
#    └─────────────────────────────────────────────┘
#
# 2. 全局变量 running
#
#    global running 声明后
#    在函数内部修改 running 会影响到全局的 running 变量
#    这允许信号处理器通知主循环退出
#
# 3. 信号处理与程序控制
#
#    问题：signal_handler在收到信号时执行
#         但主循环可能正在sleep中
#
#    解决：使用全局标志位
#    ┌─────────────────────────────────────────────┐
#    │  主循环:                                    │
#    │    while running:                          │
#    │        if not running:                    │
#    │            break  # 退出                   │
#    │        执行...                              │
#    │                                             │
#    │  信号处理:                                  │
#    │    def handler():                          │
#    │        running = False  # 通知主循环退出   │
#    │                                             │
#    │  效果：sleep结束后检测到False，退出         │
#    └─────────────────────────────────────────────┘
#
# 4. 引脚测试的重要性
#
#    在使用GPIO之前测试引脚可以：
#    - 确认引脚工作正常
#    - 发现损坏的引脚
#    - 熟悉开发板的引脚布局
