    for i in range(0, len(ALL_GPIO_PINS), 5):
        row = ALL_GPIO_PINS[i:i+5]
        pins_str = "  ".join([f"GPIO {p:2d}" for p in row])
        print(f"  {pins_str}")

    print()
    print("注意：")
    print("  - 32和33号引脚支持PWM输出")
    print("  - 某些引脚可能有特殊用途")
    print("  - 请确认开发板手册获取完整引脚定义")
    print("=" * 60)

