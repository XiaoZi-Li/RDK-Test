def main():
    """
    main - 主函数
    """

    print("=" * 60)
    print("GPIO引脚批量测试程序")
    print("=" * 60)

    # -------------------- 信号处理 --------------------
    # 注册信号处理器
    signal.signal(signal.SIGINT, signal_handler)

    # -------------------- 解析参数 --------------------
    pins = parse_arguments()

    if len(pins) == 0:
        # 用户只需要列出引脚或查看帮助
        return

    # -------------------- 测试 --------------------
    try:
        # 初始化GPIO
        GPIO.setmode(GPIO.BOARD)

        # 测试
        test_all_pins(pins)

    finally:
        # -------- 清理 --------
        GPIO.cleanup()
        print("\n所有GPIO资源已释放")

