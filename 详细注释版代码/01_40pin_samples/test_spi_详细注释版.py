# │  什么是SPI？                                                                │
# │  SPI = Serial Peripheral Interface (串行外设接口)                              │
# │  是一种高速同步串行通信协议，广泛应用于嵌入式系统                               │
# │                                                                             │
# │  SPI接线（4根基础线+片选）：                                                │
# │  - SCLK/CLK: 时钟线（主设备产生）                                            │
# │  - MOSI: 主输出从输入（Master Out Slave In）                                │
# │  - MISO: 主输入从输出（Master In Slave Out）                                │
# │  - CS/SS: 片选线（Chip Select，低电平有效）                                │
# │                                                                             │
# │  SPI的特点：                                                               │
# │  - 高速传输（可达几十MHz）                                                  │
# │  - 全双工（可以同时发送和接收）                                              │
# │  - 主从架构（主设备控制时钟）                                               │
# │  - 每个从设备需要独立的片选线                                                │
# │                                                                             │
# │  常见SPI设备：                                                             │
# │  - Flash存储器                                                             │
# │  - OLED/TFT显示屏                                                         │
