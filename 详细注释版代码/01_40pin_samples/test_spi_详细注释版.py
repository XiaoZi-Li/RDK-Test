# 第四部分：SPI测试函数
# ***************************************************************************************************

def spidevTest():
    """
    spidevTest - SPI设备测试函数

    测试流程：
    1. 获取SPI总线和设备号
    2. 打开SPI设备
    3. 配置SPI参数
    4. 发送和接收数据
    5. 关闭设备
    """

    # -------------------- 步骤1：列出可用SPI设备 --------------------
    print("\n" + "=" * 60)
    print("可用SPI控制器:")
    print("=" * 60)

    # os.system() 执行shell命令
    # ls /dev/spidev* 列出所有SPI设备
    os.system('ls -la /dev/spidev*')

    print("=" * 60)

    # -------------------- 步骤2：获取用户输入 --------------------
    # 获取SPI总线号
    # SPI总线号对应硬件连接的不同SPI控制器
    spi_bus = input("请输入SPI总线号 (例如: 0, 1, 2): ")

    # 获取片选号
    # 每个SPI总线上可以有多个从设备
    # 片选号用于选择具体是哪个从设备
    spi_device = input("请输入SPI片选号 (例如: 0, 1): ")

    # -------------------- 步骤3：打开SPI设备 --------------------
    print(f"\n正在打开SPI设备: spidev{spi_bus}.{spi_device}")

    try:
        # 创建SPI对象
        # spidev.SpiDev() 创建SPI设备对象
        spi = spidev.SpiDev()

        # 打开SPI总线
        # open(总线号, 设备号)
        # 例如: open(0, 0) 打开 /dev/spidev0.0
        spi.open(int(spi_bus), int(spi_device))

        print("SPI设备已打开!")

    except FileNotFoundError:
        print(f"错误：SPI设备 spidev{spi_bus}.{spi_device} 不存在")
        print("请检查:")
        print("  1. 内核是否支持SPI")
        print("  2. 设备树/Device Tree是否启用SPI")
        print("  3. /dev/spidev* 是否存在")
        return

    except Exception as e:
        print(f"打开SPI设备失败: {e}")
        return

    # -------------------- 步骤4：配置SPI参数 --------------------
    #
    # SPI有几个重要参数需要配置：
    #

    # 设置SPI最大时钟频率
    # 单位是Hz（赫兹）
    # 常用频率：
    # - 1 MHz = 1,000,000 Hz：通用设备
    # - 10 MHz：高速设备
    # - 20 MHz：Flash存储等
    # - 最高频率取决于从设备能力
    spi.max_speed_hz = 12000000  # 12 MHz

    # 设置SPI模式
    # SPI有4种模式，由CPOL和CPHA决定
    #
    # CPOL = 时钟极性
    #   0 = 空闲时时钟为低电平
    #   1 = 空闲时时钟为高电平
    #
    # CPHA = 时钟相位
    #   0 = 在时钟的第一个边沿采样
    #   1 = 在时钟的第二个边沿采样
    #
    # 模式组合：
    # ┌─────────────────────────────────────────────────────────────────┐
    # │ 模式  │  CPOL │  CPHA │  说明                                 │
    # ├────────┼────────┼────────┼──────────────────────────────────────┤
    # │  mode 0│   0    │   0    │  时钟低有效，第一个边沿采样           │
    # │  mode 1│   0    │   1    │  时钟低有效，第二个边沿采样           │
    # │  mode 2│   1    │   0    │  时钟高有效，第一个边沿采样           │
    # │  mode 3│   1    │   1    │  时钟高有效，第二个边沿采样           │
    # └─────────────────────────────────────────────────────────────────┘
    #
    # 大多数设备使用 mode 0 (CPOL=0, CPHA=0)
    spi.mode = 0

    # 设置每个字的位数
    # 通常是8（每个字节）
    # 某些特殊设备可能用16
    spi.bits_per_word = 8

    print(f"SPI配置:")
    print(f"  最大时钟频率: {spi.max_speed_hz} Hz ({spi.max_speed_hz/1000000} MHz)")
    print(f"  模式: {spi.mode}")
    print(f"  位/字: {spi.bits_per_word}")

    # -------------------- 步骤5：收发数据测试 --------------------
    print("\n" + "=" * 60)
    print("SPI通信测试")
    print("发送: [0x55, 0xAA] 并接收相同数据")
    print("=" * 60)

    try:
        # 准备测试数据
        # bytes() 将列表转换为字节串
        send_data = bytes([0x55, 0xAA])

        while True:
            # -------- 使用xfer2发送和接收 --------
            # spi.xfer2(数据列表)
            # 同时发送和接收数据
            # 发送和接收是同步的
            #
            # 返回值是接收到的字节列表
            recv_data = spi.xfer2(list(send_data))

            # -------- 显示结果 --------
            print(f"发送: {BytesToHex(send_data)}")
            print(f"接收: {BytesToHex(recv_data)}")

            # -------- 检查是否一致 --------
            if list(send_data) == recv_data:
                print("✓ 数据一致，SPI通信正常!")
            else:
                print("✗ 数据不一致")

            # -------- 延时 --------
            time.sleep(1)

    except KeyboardInterrupt:
        print("\n用户中断")

    finally:
        # -------- 关闭SPI --------
        spi.close()
        print("\nSPI设备已关闭")

