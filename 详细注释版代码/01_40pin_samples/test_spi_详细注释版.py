#
# 1. SPI通信原理
#
#    SPI是同步串行通信协议：
#    ┌─────────────────────────────────────────────────────────────────┐
#    │                                                                 │
#    │   主设备                          从设备                        │
#    │      │                              │                           │
#    │      │─────── SCLK (时钟) ─────────▶│                          │
#    │      │                              │                           │
#    │      │─────── MOSI (数据) ─────────▶│  ← 主机发送              │
#    │      │                              │                           │
#    │      │◀────── MISO (数据) ──────────│  → 从机发送              │
#    │      │                              │                           │
#    │      │─────── CS (片选) ───────────▶│ (低电平选中)             │
#    │                                                                 │
#    └─────────────────────────────────────────────────────────────────┘
#
#    时钟边沿采样：
#    ┌─────────────────────────────────────────────────────────────────┐
#    │                                                                 │
#    │  模式0 (CPOL=0, CPHA=0):                                       │
#    │                                                                 │
#    │  SCLK:    ─┐    ┌───────────┐    ┌─                            │
#    │           └────┘           └────┘                              │
#    │            ↑ 采样         ↑ 采样                              │
#    │                                                                 │
#    │  数据在SCLK的第一个边沿被采样                                     │
#    │                                                                 │
#    └─────────────────────────────────────────────────────────────────┘
#
# 2. 片选机制
#
#    为什么需要片选？
#    SPI总线上可以连接多个从设备
#    片选(CS)用于选择当前与主设备通信的是哪一个
#
#    ┌─────────────────────────────────────────────────────────────────┐
#    │                                                                 │
#    │           主设备                                                │
#    │              │                                                  │
#    │    ┌─────────┼─────────┐                                       │
#    │    │         │         │                                       │
#    │   SCLK    MOSI     MISO                                        │
#    │    │         │         │                                        │
#    │    ├─────────┼─────────┤                                        │
#    │    │         │         │                                        │
#    │   CS0      CS0      CS0    ← 从设备0                          │
#    │   CS1      CS1      CS1    ← 从设备1                          │
#    │   CS2      CS2      CS2    ← 从设备2                          │
#    │                                                                 │
#    │   当CS0为低电平时，只有从设备0响应                               │
#    │                                                                 │
#    └─────────────────────────────────────────────────────────────────┘
#
# 3. SPI vs I2C 对比
#
#    ┌────────────────┬─────────────┬─────────────┐
#    │ 特性           │ SPI         │ I2C         │
#    ├────────────────┼─────────────┼─────────────┤
#    │ 线数           │ 4根+        │ 2根         │
#    │ 速度           │ 几十MHz     │ 400kHz      │
#    │ 从设备数量     │ 受限于片选   │ 有限(总线)  │
#    │ 地址           │ 无(片选)    │ 需要地址     │
#    │ 全双工         │ 是          │ 半双工       │
#    │ 复杂性         │ 简单        │ 稍复杂      │
#    └────────────────┴─────────────┴─────────────┘
