def BytesToHex(Bytes):
    """
    BytesToHex - 将字节数组转换为十六进制字符串

    这是一个辅助函数
    方便我们查看SPI传输的原始数据

    参数:
        Bytes: 字节数组/列表

    返回:
        十六进制字符串，格式: "0x55 0xAA "
    """
    # 列表推导式 + join
    # 遍历每个字节，格式化为 "0x%02X " 形式
    # 最后用 ''.join() 拼接成字符串
    return ''.join(["0x%02X " % x for x in Bytes]).strip()

