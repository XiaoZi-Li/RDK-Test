# │                           《按钮事件检测》                                    │
# │                                                                             │
# │  功能说明:                                                                   │
# │  当按钮被按下时，LED灯亮起，持续1秒后自动熄灭                                  │
# │  这是一个基础的"按钮触发事件"示例                                             │
# │                                                                             │
# │  与 simple_input.py 的区别:                                                 │
# │  - simple_input.py: 循环检测状态，CPU一直在工作                              │
