# │                                                                             │
# │  硬件需求:                                                                   │
# │  - LED灯 x1（连接GPIO 31）                                                 │
# │  - 按钮 x1（连接GPIO 37）                                                   │
# │  - 330Ω电阻 x1（保护LED）                                                   │
# │                                                                             │
# │  接线图:                                                                     │
# │                                                                             │
# │  GPIO 31 ───[330Ω电阻]───[LED+]───[LED-]─── GND                           │
# │                                                                             │
# │  GPIO 37 ───[按钮]─────────────── GND                                       │
# │                                                                             │
# │  学习目标:                                                                   │
# │  1. 理解阻塞等待 vs 轮询检测                                                 │
# │  2. 学会使用 wait_for_edge 等待边沿                                         │
# │  3. 理解下降沿和上升沿的概念                                                │
# └─────────────────────────────────────────────────────────────────────────────┘

# ***************************************************************************************************
# 第一部分：导入必要的库
# ***************************************************************************************************

import sys         # 系统相关，用于程序退出
import signal      # 信号处理，用于捕获Ctrl+C
import Hobot.GPIO as GPIO  # 地平线GPIO库
import time        # 时间控制

# ***************************************************************************************************
# 第二部分：信号处理函数
# ***************************************************************************************************

def signal_handler(signal, frame):
    """
    信号处理函数 - Ctrl+C时清理退出
    """
    print("\n正在清理并退出...")
    sys.exit(0)

# ***************************************************************************************************
# 第三部分：GPIO引脚定义
# ***************************************************************************************************

# LED连接到GPIO 31号引脚（BOARD编码）
# 31号是物理引脚位置，可以在开发板上找到
led_pin = 31   # GPIO输出 - 控制LED

# 按钮连接到GPIO 37号引脚（BOARD编码）
# 按钮另一端接地（GND）
but_pin = 37   # GPIO输入 - 读取按钮状态

# 禁用警告信息
GPIO.setwarnings(False)

# ***************************************************************************************************
# 第四部分：主函数
# ***************************************************************************************************

def main():
    """
    主函数 - 按钮事件检测

    程序流程：
    1. 设置GPIO模式
    2. 配置LED为输出，按钮为输入
    3. LED初始关闭
    4. 无限循环等待按钮按下事件
    5. 按钮按下 → LED亮1秒 → LED灭 → 继续等待

    ┌─────────────────────────────────────────────────────────────┐
    │                     程序流程图                               │
    │                                                             │
    │   ┌─────────────┐                                          │
    │   │   开始      │                                          │
    │   └──────┬──────┘                                          │
    │          ↓                                                 │
    │   ┌─────────────┐                                          │
    │   │  初始化GPIO │                                          │
    │   │  LED=输出    │                                          │
    │   │  按钮=输入   │                                          │
    │   │  LED=关闭    │                                          │
    │   └──────┬──────┘                                          │
    │          ↓                                                 │
    │   ┌─────────────┐                                          │
    │   │ 等待按钮按下 │◄───────────────────┐                   │
    │   │(wait_for_edge)│                    │                   │
    │   └──────┬──────┘                    │                   │
    │          ↓                             │                   │
    │   ┌─────────────┐                     │                   │
    │   │  按钮被按下! │                     │                   │
    │   └──────┬──────┘                     │                   │
    │          ↓                             │                   │
    │   ┌─────────────┐                     │                   │
    │   │  LED = 亮   │                     │                   │
    │   │  延时1秒    │                     │                   │
    │   └──────┬──────┘                     │                   │
    │          ↓                             │                   │
    │   ┌─────────────┐                     │                   │
    │   │  LED = 灭   │─────────────────────┘                   │
    │   └─────────────┘     (返回继续等待)                       │
    │                                                             │
    └─────────────────────────────────────────────────────────────┘
    """

    # -------------------- 步骤1：设置GPIO模式 --------------------
    GPIO.setmode(GPIO.BOARD)

    # -------------------- 步骤2：配置LED为输出 --------------------
    # LED引脚设置为输出模式
    # initial=GPIO.HIGH 表示初始电平为高（LED灭）
    # 为什么初始是HIGH而不是LOW？因为LED正极接3.3V
    # HIGH时两边都是3.3V，没有电压差，LED不亮
    GPIO.setup(led_pin, GPIO.OUT, initial=GPIO.HIGH)

    # -------------------- 步骤3：配置按钮为输入 --------------------
    # 按钮引脚设置为输入模式
    # 默认不需要上下拉，因为按钮直接接地/接3.3V
    GPIO.setup(but_pin, GPIO.IN)

    # -------------------- 步骤4：关闭LED --------------------
    # 确保LED初始状态是关闭的
    GPIO.output(led_pin, GPIO.LOW)  # LOW时，GPIO接地，LED亮
    # 等等，这里逻辑有点绕，让我解释一下：
    # 如果LED正极接3.3V，负极接GPIO
    # GPIO=HIGH → 负极也是3.3V → 没有电压差 → LED灭
    # GPIO=LOW → 负极接地(0V) → 有电压差 → LED亮
    # 所以：GPIO.LOW = LED亮，GPIO.HIGH = LED灭

    # 重新设置为正确的初始状态
    GPIO.output(led_pin, GPIO.HIGH)  # 初始LED灭

    # -------------------- 步骤5：打印欢迎信息 --------------------
    print("=" * 60)
    print("按钮事件检测示例")
    print("=" * 60)
    print(f"LED引脚: GPIO {led_pin} (BOARD)")
    print(f"按钮引脚: GPIO {but_pin} (BOARD)")
    print("按下按钮，LED会亮1秒后熄灭")
    print("=" * 60)
    print("按 Ctrl+C 退出程序")
    print("=" * 60)

    # -------------------- 步骤6：主循环 --------------------
    try:
        while True:
            # 打印等待信息
            print("等待按钮按下...")

            # -------- 等待按钮按下 --------
            # GPIO.wait_for_edge() 是一个阻塞函数
            # 它会暂停程序执行，直到指定边沿出现
            #
            # 参数说明：
            # - but_pin: 监测的引脚
            # - GPIO.FALLING: 下降沿触发
            #
            # 什么是下降沿？
            # 电平从 HIGH(1) 变为 LOW(0) 的瞬间
            # 也就是按钮按下时触发的边沿
            #
            # 边沿类型：
            # - GPIO.RISING:  上升沿 (0→1) - 按钮松开时
            # - GPIO.FALLING: 下降沿 (1→0) - 按钮按下时
            # - GPIO.BOTH:    两种边沿都触发
            #
            # 为什么用FALLING而不是RISING？
            # 因为按钮按下时GPIO接地变LOW（下降沿）
            # 按钮松开时GPIO恢复高电平（上升沿）
            # 我们希望检测"按下"动作，所以用FALLING
            GPIO.wait_for_edge(but_pin, GPIO.FALLING)

            # -------- 按钮被按下了！--------
            print("检测到按钮按下！")

            # -------- 点亮LED --------
            # 将GPIO设置为LOW，LED亮起
            GPIO.output(led_pin, GPIO.LOW)

            # -------- 延时1秒 --------
            # LED保持亮起1秒
            time.sleep(1)

            # -------- 关闭LED --------
            # 将GPIO设置为HIGH，LED熄灭
            GPIO.output(led_pin, GPIO.HIGH)

            # -------- 循环回到等待状态 --------
            # 继续等待下一次按钮按下

    finally:
        # -------- 清理 --------
        GPIO.cleanup()
        print("\nGPIO已清理，程序退出")

# ***************************************************************************************************
# 第五部分：程序入口
# ***************************************************************************************************

if __name__ == '__main__':
    signal.signal(signal.SIGINT, signal_handler)
    main()

# ***************************************************************************************************
# 知识详解
# ***************************************************************************************************
#
# 1. 阻塞等待 vs 轮询检测
#
#    轮询检测（simple_input.py的方法）：
#    ┌─────────────────────────────────────────────┐
#    │  while True:                               │
#    │      value = GPIO.input(pin)  # 一直读     │
#    │      if value != prev:        # 检查变化    │
#    │          处理...                            │
#    │      time.sleep(1)             # 延时       │
#    │                                             │
#    │  缺点：CPU一直在工作，浪费资源              │
#    │  优点：可以同时检测多个事件                  │
#    └─────────────────────────────────────────────┘
#
#    阻塞等待（wait_for_edge）：
#    ┌─────────────────────────────────────────────┐
#    │  while True:                               │
#    │      GPIO.wait_for_edge(pin)  # 等待！      │
#    │      处理...                               │
#    │                                             │
#    │  优点：CPU可以休息，节省资源                │
#    │  缺点：只能等一个事件                      │
#    └─────────────────────────────────────────────┘
#
# 2. 边沿检测的原理
#
#    边沿 = 电平跳变的瞬间
#
#    ┌─────────────────────────────────────────────┐
#    │                                             │
#    │  上升沿 RISING  (FALLING的镜像)             │
#    │    │                                       │
#    │    │ ← 0→1 上升                            │
#    │    ↓                                       │
#    │  ┌─────────────────────────────────┐       │
#    │  │ HIGH (1)                    ~~~ │       │
#    │  └─────────────────────────────────┘       │
#    │                                       │   │
#    │                                    → │   │
#    │                                       ↓   │
#    │                                    LOW(0) │
#    │                                             │
#    │  下降沿 FALLING                            │
#    │    ↓                                       │
#    │    │ ← 1→0 下降                            │
#    │    │                                       │
#    │  ┌─────────────────────────────────┐       │
#    │  │ HIGH (1) ~~~~~~~~~~~~~~~~~~    │       │
#    │  └─────────────────────────────────┘       │
#    │                                             │
#    │  时钟周期                                  │
#    │    ──┬──┬──┬──┬──┬──┬──┬──┬───            │
#    │      │  │  │  │  │  │  │  │  │            │
#    │                                             │
#    │  下降沿和上升沿都是"时刻"，不是"状态"        │
#    └─────────────────────────────────────────────┘
#
# 3. 按钮的电气特性
#
#    理想的按钮：
#    ┌─────────────────────────────────────────────┐
#    │  按下: 短路 (0Ω)                            │
#    │  松开: 断路 (∞Ω)                            │
#    └─────────────────────────────────────────────┘
#
#    实际的按钮（有抖动）：
#    ┌─────────────────────────────────────────────┐
#    │  按下时触点会弹跳几次                         │
#    │                                             │
#    │  ────┐    ┌───┐                            │
#    │      └┘    └─┘ └─  抖动                     │
#    │                                             │
#    │  抖动时间：5-10ms                          │
#    │  可能导致多次触发                            │
#    └─────────────────────────────────────────────┘
#
#    解决方案：
#    1. 硬件去抖：并联电容
#    2. 软件去抖：延时后再检测
#
