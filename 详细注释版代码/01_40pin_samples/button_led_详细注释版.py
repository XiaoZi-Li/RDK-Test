# │  功能说明:                                                                   │
# │  最简单的按钮控制LED：按下按钮LED亮，松开LED灭                                  │
# │  实时响应，没有延时                                                            │
# │                                                                             │
# │  这个程序展示了最基本的输入->输出逻辑                                           │
# │  是理解自动控制的好起点                                                       │
# │                                                                             │
# │  硬件需求:                                                                   │
# │  - LED灯 x1（接GPIO 31）                                                   │
# │  - 按钮 x1（接GPIO 37）                                                    │
# │                                                                             │
# │  接线:                                                                       │
# │  GPIO 31 ───[330Ω电阻]───[LED]─── GND                                     │
# │  GPIO 37 ───[按钮]─────────── GND                                          │
# │                                                                             │
# │  工作原理:                                                                   │
# │  ┌─────────────────────────────────────────────────────────┐              │
# │  │                                                         │              │
# │  │   循环读取按钮状态 ──→ 根据状态设置LED                  │              │
# │  │         ↑                          │                    │              │
# │  │         └────────循环──────────────┘                    │              │
# │  │                                                         │              │
# │  │   按下按钮 → GPIO37=GND → 读取LOW → LED亮              │              │
# │  │   松开按钮 → GPIO37=3.3V → 读取HIGH → LED灭            │              │
# │  │                                                         │              │
# │  └─────────────────────────────────────────────────────────┘              │
# │                                                                             │
# │  学习目标:                                                                   │
# │  1. 理解输入到输出的映射关系                                                 │
# │  2. 理解实时响应vs延时响应                                                   │
# └─────────────────────────────────────────────────────────────────────────────┘

# ***************************************************************************************************
# 第一部分：导入必要的库
# ***************************************************************************************************

import sys         # 系统相关
import signal      # 信号处理
import Hobot.GPIO as GPIO  # GPIO库
import time        # 时间控制

# ***************************************************************************************************
# 第二部分：信号处理
# ***************************************************************************************************

def signal_handler(signal, frame):
    """
    Ctrl+C 信号处理器 - 清理退出
    """
    print("\n正在清理并退出...")
    sys.exit(0)

# ***************************************************************************************************
# 第三部分：引脚定义
# ***************************************************************************************************

led_pin = 31   # LED引脚
but_pin = 37   # 按钮引脚

# 禁用警告
GPIO.setwarnings(False)

# ***************************************************************************************************
# 第四部分：主函数
# ***************************************************************************************************

def main():
    """
    main - 主函数

    程序逻辑（超级简单）：
    ┌─────────────────────────────────────────────────────────┐
    │                                                         │
    │   while True:                                         │
    │       读取按钮状态                                     │
    │           │                                           │
    │           ↓                                           │
    │       如果按钮被按下（LOW）                           │
    │           │                                           │
    │           ↓                                           │
    │       LED = 亮                                        │
    │           │                                           │
    │       否则（松开，HIGH）                               │
    │           │                                           │
    │           ↓                                           │
    │       LED = 灭                                        │
    │                                                         │
    └─────────────────────────────────────────────────────────┘

    这是一个典型的"连续监控+条件执行"模式
    """

    # -------------------- 步骤1：初始化GPIO --------------------
    GPIO.setmode(GPIO.BOARD)

    # -------------------- 步骤2：配置引脚 --------------------
    GPIO.setup(led_pin, GPIO.OUT)  # LED为输出
    GPIO.setup(but_pin, GPIO.IN)   # 按钮为输入

    # -------------------- 步骤3：初始状态 --------------------
    GPIO.output(led_pin, GPIO.HIGH)  # LED初始灭

    # -------------------- 步骤4：打印信息 --------------------
    print("=" * 60)
    print("按钮直接控制LED示例")
    print("=" * 60)
    print("按住按钮LED亮，松开LED灭")
    print("=" * 60)
    print("按 Ctrl+C 退出")
    print("=" * 60)

    # -------------------- 步骤5：主循环 --------------------
    prev_value = None  # 记录上次状态，用于检测变化

    try:
        while True:
            # -------- 读取按钮状态 --------
            # GPIO.input(引脚) 返回当前电平
            # 按下按钮 = LOW (0V)
            # 松开按钮 = HIGH (3.3V)
            curr_value = GPIO.input(but_pin)

            # -------- 设置LED状态 --------
            # LED逻辑与按钮相反：
            # 按钮按下(LOW) → LED亮
            # 按钮松开(HIGH) → LED灭
            #
            # 直接把按钮的状态赋给LED
            # 因为：GPIO.LOW = 0V = LED负极接地 = LED亮
            #      GPIO.HIGH = 3.3V = 无电压差 = LED灭
            GPIO.output(led_pin, curr_value)

            # -------- 状态变化时打印 --------
            # 只有状态变化时才打印，避免刷屏
            if curr_value != prev_value:
                if curr_value == GPIO.LOW:
                    print("按钮: 按下 → LED: 亮")
                else:
                    print("按钮: 松开 → LED: 灭")
                prev_value = curr_value

            # -------- 快速检测 --------
            # 延时1秒太长了
            # 改成10ms，可以更快响应
            time.sleep(0.01)  # 10ms

    finally:
        GPIO.cleanup()
        print("\n程序已退出")

# ***************************************************************************************************
# 第五部分：程序入口
# ***************************************************************************************************

if __name__ == '__main__':
    signal.signal(signal.SIGINT, signal_handler)
    main()

# ***************************************************************************************************
# 对比分析
# ***************************************************************************************************
#
# 三种按钮处理方式的对比：
#
# 1. simple_input.py - 轮询检测
#    ┌─────────────────────────────────────────────┐
#    │  while True:                               │
#    │      value = GPIO.input(pin)              │
#    │      处理...                               │
#    │  特点：一直在读取，响应稍慢                  │
#    └─────────────────────────────────────────────┘
#
# 2. button_event.py - 阻塞等待
#    ┌─────────────────────────────────────────────┐
#    │  while True:                               │
#    │      wait_for_edge()  # 等待时CPU休息       │
#    │      处理...                               │
#    │  特点：按下才处理，CPU空闲                  │
#    └─────────────────────────────────────────────┘
#
# 3. button_led.py - 实时控制
#    ┌─────────────────────────────────────────────┐
#    │  while True:                               │
#    │      读取 → 判断 → 输出                     │
#    │  特点：实时响应，每时每刻都在检测             │
#    └─────────────────────────────────────────────┘
#
# 适合场景：
# ┌────────────────┬─────────────────────────────────┐
# │ 方式           │  适合场景                       │
# ├────────────────┼─────────────────────────────────┤
# │ 轮询检测       │  需要同时检测多个按钮             │
# │ 阻塞等待       │  等待特定事件，不需要一直处理     │
# │ 实时控制       │  即时响应，简单的输入输出映射     │
# └────────────────┴─────────────────────────────────┘
#
# ***************************************************************************************************
# 课后练习
# ***************************************************************************************************
#
# 练习1：改变响应速度
#   time.sleep(0.01) 改成更小或更大的值
#   注意：太小会占用CPU，太大响应会慢
#
# 练习2：反过来控制（按下灭，松开亮）
#   GPIO.output(led_pin, 1 - curr_value)
#   或 GPIO.output(led_pin, not curr_value)
#
# 练习3：添加指示灯
#   再加一个LED，表示程序运行状态
#   每秒闪烁一次
#
# 练习4：反转逻辑（按下灭，松开亮）
#   按钮逻辑和LED逻辑相反
#   curr_value == GPIO.LOW → LED灭
#   curr_value == GPIO.HIGH → LED亮
#
# ***************************************************************************************************
# 常见问题
# ***************************************************************************************************
#
# Q: LED反应有延迟？
#   time.sleep() 值太大
#   改成 0.001 或 0.005
#
# Q: 按钮按下时LED亮，但有闪烁？
#   可能是按钮抖动
#   添加简单的延时去抖
#
# Q: CPU占用率高？
#   time.sleep() 值太小
#   改成 0.01 或 0.02
#
# ***************************************************************************************************

print("=" * 60)
print("恭喜完成！这是最简单的按钮控制LED")
print("=" * 60)
