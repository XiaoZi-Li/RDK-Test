# │  功能说明:                                                                   │
# │  使用中断方式检测按钮，按下时LED快速闪烁5次                                    │
# │  与 button_event.py 的区别是使用了"中断检测"而非"阻塞等待"                    │
# │                                                                             │
# │  什么是中断？                                                                │
# │  中断是一种机制：当特定事件发生时，CPU暂停当前工作，去处理这个事件              │
# │  就像你正在工作时，突然门铃响了（中断），你去开门（处理），然后回来继续工作      │
# │                                                                             │
# │  优点：                                                                     │
# │  - CPU不需要一直查询（polling），节省资源                                    │
# │  - 响应速度快，事件一发生就能立即处理                                        │
# │  - 可以同时处理多个中断源                                                    │
# │                                                                             │
# │  硬件需求:                                                                   │
# │  - LED灯 x2（LED1接GPIO 15，LED2接GPIO 16）                                │
# │  - 按钮 x1（接GPIO 37）                                                    │
# │                                                                             │
# │  学习目标:                                                                   │
# │  1. 理解中断的概念                                                          │
# │  2. 学会使用 add_event_detect 注册中断                                     │
