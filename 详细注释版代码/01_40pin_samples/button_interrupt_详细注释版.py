# │  4. 理解消抖处理                                                           │
# └─────────────────────────────────────────────────────────────────────────────┘

# ***************************************************************************************************
# 第一部分：导入必要的库
# ***************************************************************************************************

import sys         # 系统相关
import signal      # 信号处理
import Hobot.GPIO as GPIO  # GPIO库
import time        # 时间控制

# ***************************************************************************************************
# 第二部分：信号处理函数
# ***************************************************************************************************

def signal_handler(signal, frame):
    """
    Ctrl+C 信号处理器
    确保程序退出时清理GPIO资源
    """
    print("\n正在清理并退出...")
    sys.exit(0)

# ***************************************************************************************************
# 第三部分：GPIO引脚定义
# ***************************************************************************************************

led_pin_1 = 15   # LED1: GPIO 15号引脚 - 正常工作LED（缓慢闪烁）
led_pin_2 = 16   # LED2: GPIO 16号引脚 - 中断触发LED（快速闪烁）
but_pin = 37     # 按钮: GPIO 37号引脚

# 禁用警告
GPIO.setwarnings(False)

# ***************************************************************************************************
# 第四部分：中断回调函数
# ***************************************************************************************************

def blink(channel):
    """
    blink - 中断回调函数

    重要概念：
    这个函数不是我们主动调用的
    而是当按钮按下（中断发生）时，由系统自动调用的

    这种函数叫做"回调函数"（Callback Function）
    "回调"的意思是：你把函数地址告诉系统，系统在需要时回头调用你

    参数:
        channel: 触发中断的引脚号（这里我们不用，但必须有）

    这个函数会：
    1. 打印一条消息
    2. 让LED2快速闪烁5次
    """

    print(f"检测到按钮按下！触发中断，引脚: {channel}")

    # 快速闪烁5次
    for i in range(5):
        GPIO.output(led_pin_2, GPIO.HIGH)  # LED灭
        time.sleep(0.5)  # 500ms
        GPIO.output(led_pin_2, GPIO.LOW)   # LED亮
        time.sleep(0.5)  # 500ms

    # 确保LED最后是熄灭状态
    GPIO.output(led_pin_2, GPIO.HIGH)

# ***************************************************************************************************
# 第五部分：主函数
# ***************************************************************************************************

def main():
    """
    main - 主函数

    程序流程：
    1. 初始化GPIO
    2. 配置引脚模式
    3. 注册中断处理函数
    4. 主循环：LED1缓慢闪烁
    5. 当按钮按下时，触发中断，LED2快速闪烁

    ┌─────────────────────────────────────────────────────────────────┐
    │                      程序架构图                                   │
    │                                                                 │
    │  ┌─────────────────────────────────────────────────────────┐   │
    │  │                    主程序                                 │   │
    │  │                                                         │   │
    │  │   while True:                                          │   │
    │  │       LED1缓慢闪烁                                       │   │
    │  │       (主循环)                                          │   │
    │  │                                                         │   │
    │  └─────────────────────────────────────────────────────────┘   │
    │              ↑                              ↓                   │
    │              │     register_callback      中断触发              │
    │              │                              ↓                   │
    │  ┌─────────────────────────────────────────────────────────┐   │
    │  │                   中断处理函数                            │   │
    │  │                   blink()                               │   │
    │  │                   LED2快速闪烁5次                        │   │
    │  └─────────────────────────────────────────────────────────┘   │
    │                                                                 │
    └─────────────────────────────────────────────────────────────────┘
    """

    # -------------------- 步骤1：设置GPIO模式 --------------------
    GPIO.setmode(GPIO.BOARD)

    # -------------------- 步骤2：配置LED为输出 --------------------
    GPIO.setup(led_pin_1, GPIO.OUT)
    GPIO.setup(led_pin_2, GPIO.OUT)

    # -------------------- 步骤3：配置按钮为输入 --------------------
    GPIO.setup(but_pin, GPIO.IN)

    # -------------------- 步骤4：初始化LED状态 --------------------
    GPIO.output(led_pin_1, GPIO.HIGH)  # LED1初始灭
    GPIO.output(led_pin_2, GPIO.HIGH)  # LED2初始灭

    # -------------------- 步骤5：注册中断处理 --------------------
    #
    # GPIO.add_event_detect() 是注册中断处理的核心函数
    #
    # 参数说明：
    # - but_pin: 要监测的引脚
    # - GPIO.FALLING: 触发的边沿类型
    #   - GPIO.RISING:  上升沿（0→1）
    #   - GPIO.FALLING: 下降沿（1→0）= 按钮按下
    #   - GPIO.BOTH:    两种边沿都触发
    # - callback=blink: 回调函数，中断触发时调用
    # - bouncetime=10: 消抖时间（毫秒）
    #
    # 消抖说明：
    # 机械按钮按下时会有抖动
    # bouncetime=10 表示在10ms内忽略后续触发
    # 这样可以避免按钮按一次却触发多次的问题
    #
    GPIO.add_event_detect(
        but_pin,                          # 监测的引脚
        GPIO.FALLING,                     # 下降沿触发（按钮按下）
        callback=blink,                   # 回调函数
        bouncetime=10                     # 消抖时间10ms
    )

    # -------------------- 步骤6：打印欢迎信息 --------------------
    print("=" * 60)
    print("GPIO中断处理示例")
    print("=" * 60)
    print(f"LED1引脚: GPIO {led_pin_1} (BOARD) - 主循环缓慢闪烁")
    print(f"LED2引脚: GPIO {led_pin_2} (BOARD) - 中断触发快速闪烁")
    print(f"按钮引脚: GPIO {but_pin} (BOARD)")
    print("=" * 60)
    print("按下按钮，LED2会快速闪烁5次")
    print("同时LED1会继续缓慢闪烁")
    print("=" * 60)
    print("按 Ctrl+C 退出程序")
    print("=" * 60)

    # -------------------- 步骤7：主循环 --------------------
    try:
        while True:
            # LED1 缓慢闪烁（每2秒切换一次）
            # 这个循环在不断执行
            # 当按钮按下时，会触发中断
            # 中断处理在另一个函数中进行
            # 两边互不干扰
            GPIO.output(led_pin_1, GPIO.HIGH)
            time.sleep(2)
            GPIO.output(led_pin_1, GPIO.LOW)
            time.sleep(2)

    finally:
        # -------- 清理 --------
        # 移除中断检测
        GPIO.remove_event_detect(but_pin)
        # 清理GPIO
        GPIO.cleanup()
        print("\nGPIO已清理，程序退出")

# ***************************************************************************************************
# 第六部分：程序入口
# ***************************************************************************************************

if __name__ == '__main__':
    signal.signal(signal.SIGINT, signal_handler)
    main()

# ***************************************************************************************************
# 知识详解
# ***************************************************************************************************
#
# 1. 中断 vs 轮询
#
#    轮询（Polling）方式：
#    ┌─────────────────────────────────────────────┐
#    │  while True:                               │
#    │      if 按钮按下:                          │
#    │          处理...                           │
#    │      else:                                 │
#    │          继续等待...                       │
#    │                                             │
#    │  CPU一直在跑，累！                         │
#    └─────────────────────────────────────────────┘
#
#    中断（Interrupt）方式：
#    ┌─────────────────────────────────────────────┐
#    │  def 中断处理函数():                        │
#    │      处理中断...                            │
#    │                                             │
#    │  while True:                               │
#    │      做其他事情...  ← CPU可以干别的         │
#    │                                             │
#    │  系统: "按钮按下了！" → 调用中断处理函数    │
#    └─────────────────────────────────────────────┘
#
#    对比：
#    ┌────────────────┬─────────────┬─────────────┐
#    │                │  轮询方式    │  中断方式    │
#    ├────────────────┼─────────────┼─────────────┤
#    │ CPU占用        │  高         │  低          │
#    │ 响应速度       │  取决于轮询  │  立即响应    │
#    │ 代码复杂度     │  简单        │  稍复杂      │
#    │ 适合场景      │  快速轮询   │  事件驱动    │
#    └────────────────┴─────────────┴─────────────┘
#
# 2. 回调函数机制
#
#    回调函数就像订外卖：
#    ┌─────────────────────────────────────────────┐
#    │                                             │
#    │  你（主程序）：                             │
#    │    "老板，来份炒饭" ← 告诉系统你要什么      │
#    │                                             │
#    │  老板（系统）：                             │
#    │    "好的，做好了给你送过去"                 │
#    │                                             │
#    │  你继续：                                   │
#    │    打游戏、看电视... ← 做自己的事情         │
#    │                                             │
#    │  门铃响（中断触发）：                        │
#    │    "你的外卖到了！" ← 系统回调你            │
#    │    开门取外卖...                            │
#    │                                             │
#    └─────────────────────────────────────────────┘
#
# 3. 中断的优先级
#
#    如果有多个中断同时发生怎么办？
#    - 中断有优先级，高优先级的中断先处理
#    - 非常高的优先级的中断可以"打断"正在处理的中断
#    - 大多数情况下，我们的中断优先级是平等的
#
# 4. 消抖的必要性
#
#    机械按钮的抖动会导致：
#    ┌─────────────────────────────────────────────┐
#    │ 理想情况：按一次 → 触发一次                  │
#    │                                             │
#    │ 实际情况：按一次 → 触发 × 3-5 次            │
#    │           ↓抖动↓                            │
#    │           __─└─┘ └─┘ ┘__                    │
#    │           触 触 触 触                        │
#    └─────────────────────────────────────────────┘
#
#    bouncetime 参数的作用：
#    - 设置一个"锁定时间"
#    - 触发一次后，接下来N毫秒内忽略再次触发
#    - 抖动结束后才会响应下一次按下
#
