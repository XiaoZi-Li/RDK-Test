#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
simple_input.py - GPIO输入读取示例
================================================================================

【程序功能】
本程序演示如何读取GPIO管脚的输入电平状态。通过循环检测GPIO 37号管脚的电平变化，
当电平状态发生改变时打印当前状态（高电平或低电平）。

【硬件连接】
- 使用BOARD编码方式的37号管脚
- 该管脚需要连接到高低电平源（如按键、传感器等）
- 或者将管脚悬空（可能读到不确定的值）

【 BOARD编码 vs BCM编码 】
- BOARD编码：使用开发板上标注的物理管脚号（如37），直观但因板子而异
- BCM编码：使用Broadcom芯片的GPIO编号（如26），需要查表

【电平状态】
- GPIO.HIGH (1): 高电平，表示电压为3.3V
- GPIO.LOW (0): 低电平，表示电压为0V

【运行方式】
sudo python3 simple_input.py

【效果】
每1秒检测一次管脚电平，状态变化时打印：
Value read from pin 37 : HIGH
Value read from pin 37 : LOW

================================================================================
"""

import sys
import signal
import Hobot.GPIO as GPIO
import time

def signal_handler(signal, frame):
    """
    信号处理器 - 处理Ctrl+C退出信号

    【功能】
        当用户按下Ctrl+C时，优雅地退出程序
        确保GPIO资源被正确释放
    """
    sys.exit(0)

# ================================================================================
# 主程序开始
# ================================================================================

# -----------------------------------------------------------------------------
# 第1步：注册Ctrl+C信号处理器
# -----------------------------------------------------------------------------
# 捕获SIGINT信号（Ctrl+C），确保程序退出时能正确清理GPIO资源
signal.signal(signal.SIGINT, signal_handler)

# -----------------------------------------------------------------------------
# 第2步：定义使用的GPIO管脚
# -----------------------------------------------------------------------------
# BOARD编码方式的37号管脚
# 物理管脚37对应BCM编码的26号（如果使用BCM模式需要用GPIO 26）
input_pin = 37

# -----------------------------------------------------------------------------
# 第3步：禁用GPIO警告信息（可选）
# -----------------------------------------------------------------------------
# 当管脚已经被其他程序占用时，GPIO库会发出警告
# setwarnings(False)可以禁用这些警告，使输出更简洁
GPIO.setwarnings(False)

def main():
    """
    主函数 - 循环读取GPIO输入状态

    【工作流程】
        1. 设置GPIO模式为BOARD
        2. 配置管脚为输入模式
        3. 循环读取电平状态
        4. 状态变化时打印信息
        5. 每次sleep 1秒
    """
    # 保存上一个状态，用于检测变化
    prev_value = None

    # -----------------------------------------------------------------------------
    # 第4步：设置GPIO模式
    # -----------------------------------------------------------------------------
    # GPIO.BOARD: 使用BOARD物理管脚编码方式
    # 其他选项：GPIO.BCM - 使用Broadcom GPIO编号
    GPIO.setmode(GPIO.BOARD)

    # -----------------------------------------------------------------------------
    # 第5步：配置管脚为输入模式
    # -----------------------------------------------------------------------------
    # GPIO.IN: 将管脚配置为输入模式
    # 这样可以读取管脚上的外部电平信号
    GPIO.setup(input_pin, GPIO.IN)

    print("Starting demo now! Press CTRL+C to exit")

    try:
        # -----------------------------------------------------------------------------
        # 第6步：主循环 - 持续检测电平变化
        # -----------------------------------------------------------------------------
        while True:
            # 读取管脚当前电平值
            # 返回GPIO.HIGH(1)或GPIO.LOW(0)
            value = GPIO.input(input_pin)

            # 只有当电平状态发生变化时才打印
            if value != prev_value:
                # 将数值转换为可读字符串
                if value == GPIO.HIGH:
                    value_str = "HIGH"  # 高电平，电压约3.3V
                else:
                    value_str = "LOW"   # 低电平，电压约0V

                # 打印当前管脚和电平状态
                print("Value read from pin {} : {}".format(input_pin, value_str))

                # 更新上一个状态值
                prev_value = value

            # -----------------------------------------------------------------------------
            # 第7步：延时1秒后继续检测
            # -----------------------------------------------------------------------------
            # time.sleep(1) 让程序暂停1秒
            # 这可以：
            # 1. 避免过度消耗CPU资源
            # 2. 给电平信号稳定的时间
            time.sleep(1)

    finally:
        # -----------------------------------------------------------------------------
        # 第8步：清理GPIO资源
        # -----------------------------------------------------------------------------
        # 确保程序退出时释放GPIO管脚
        # 无论正常退出还是Ctrl+C都会执行这里
        GPIO.cleanup()

# ================================================================================
# 程序入口
# ================================================================================

if __name__ == '__main__':
    main()

# ================================================================================
# 【GPIO输入模式详解】
# ================================================================================
# GPIO输入模式用于读取外部信号的电平状态
#
# 1. 上拉/下拉电阻
#    - 上拉电阻：将管脚默认拉到高电平
#    - 下拉电阻：将管脚默认拉到低电平
#    - 有些GPIO管脚内部集成上拉/下拉电阻
#
# 2. 防抖处理
#    - 机械开关在状态切换时会有抖动
#    - 可以用硬件消抖或软件延时处理
#
# 3. 浮空输入
#    - 管脚悬空时读到的值不确定
#    - 建议始终连接确定的上拉或下拉电阻
#
# 【注意事项】
# - 读取输入时不会改变管脚状态
# - 输入模式下不能输出电压
# - 不要连接超过3.3V的电压到输入管脚
