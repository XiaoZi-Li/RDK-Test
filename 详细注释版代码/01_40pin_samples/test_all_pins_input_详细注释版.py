#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
test_all_pins_input.py - GPIO所有管脚输入测试程序
================================================================================

【程序功能】
本程序用于测试开发板上所有可用的GPIO（通用输入输出）管脚的输入功能。
它会遍历指定的GPIO管脚，读取并打印每个管脚当前的电平状态（高电平或低电平）。

【硬件连接】
- 需要将GPIO管脚连接到高低电平源（如按键、传感器输出等）
- 或者将管脚悬空（可能读取引脚浮空值）

【使用场景】
1. 硬件调试：验证GPIO管脚是否正常工作
2. 引脚检测：确认某个管脚当前电平状态
3. 传感器测试：读取数字传感器输出的高低电平

【运行方式】
# 测试所有管脚
python3 test_all_pins_input.py

# 只测试指定的管脚（管脚号根据BOARD编号）
python3 test_all_pins_input.py 7 11 12 13 15

================================================================================
"""

from __future__ import print_function
import sys
import signal
import Hobot.GPIO as GPIO

def signal_handler(signal, frame):
    """
    信号处理器 - 处理Ctrl+C退出信号

    【参数】
        signal: 信号类型
        frame: 当前栈帧

    【功能】
        当用户按下Ctrl+C时，优雅地退出程序，避免管脚状态异常
    """
    sys.exit(0)

# ================================================================================
# 主程序开始
# ================================================================================

# -----------------------------------------------------------------------------
# 第1步：注册Ctrl+C信号处理器
# -----------------------------------------------------------------------------
# 捕获SIGINT信号（Ctrl+C），确保程序退出时能正确清理GPIO资源
signal.signal(signal.SIGINT, signal_handler)

# -----------------------------------------------------------------------------
# 第2步：获取可用的GPIO管脚列表
# -----------------------------------------------------------------------------
# all_pin_data['BOARD']: 以BOARD编号方式访问的所有可用管脚字典
# BOARD编号方式使用板子上标注的物理管脚号（如7、11、12等）
all_pins = list(GPIO.all_pin_data['BOARD'].keys())
all_pins.sort()

# -----------------------------------------------------------------------------
# 第3步：解析命令行参数（可选）
# -----------------------------------------------------------------------------
# 如果用户指定了命令行参数，则只测试指定的管脚
# sys.argv[0] 是脚本本身，sys.argv[1:]是用户传入的管脚号列表
# 用法示例：python3 test_all_pins_input.py 7 11 12
if len(sys.argv) > 1:
    # 将命令行参数转换为整数管脚号列表
    all_pins = map(int, sys.argv[1:])

print("All gpio pins: ", all_pins)

# -----------------------------------------------------------------------------
# 第4步：禁用GPIO警告信息（可选）
# -----------------------------------------------------------------------------
# 当管脚已经被其他程序占用时，GPIO库会发出警告
# setwarnings(False)可以禁用这些警告，使输出更简洁
GPIO.setwarnings(False)

# -----------------------------------------------------------------------------
# 第5步：遍历所有管脚并读取输入电平
# -----------------------------------------------------------------------------
for pin in all_pins:
    # 设置GPIO模式为BOARD编号方式
    GPIO.setmode(GPIO.BOARD)

    # 将管脚配置为输入模式
    # GPIO.IN: 将管脚设置为输入模式，用于读取电平状态
    GPIO.setup(pin, GPIO.IN)

    # 读取管脚的当前电平值
    # GPIO.HIGH (或 1): 高电平，表示电压为3.3V或5V
    # GPIO.LOW (或 0): 低电平，表示电压为0V
    value = GPIO.input(pin)

    # 打印管脚号和对应的电平值
    print("Pin %d input value %d" % (pin, value))

    # 清理管脚配置
    # 每次读取后清理管脚，确保不影响下次使用
    # 在BOARD模式下，cleanup()不带参数会清理所有已使用的管脚
    GPIO.cleanup()

# -----------------------------------------------------------------------------
# 【总结】
# -----------------------------------------------------------------------------
# 本程序展示了GPIO输入的基本操作流程：
# 1. 获取可用管脚列表
# 2. 设置GPIO模式（BOARD或BCM）
# 3. 配置管脚方向（输入/输出）
# 4. 读取电平值
# 5. 清理管脚资源
#
# 【注意事项】
# - 确保管脚连接正确，不要连接强电压（>3.3V或>5V取决于开发板）
# - 输入模式下管脚悬空可能读到不确定的值
# - 某些管脚可能有特定功能（如I2C、SPI），使用前请确认
