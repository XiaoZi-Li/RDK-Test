# ***************************************************************************************************
# 第三部分：I2C设备测试函数
# ***************************************************************************************************

def i2cdevTest():
    """
    i2cdevTest - I2C设备测试函数

    这个函数会：
    1. 显示可用的I2C控制器
    2. 让用户选择要测试的I2C总线
    3. 扫描总线上的设备
    4. 进行简单的读写测试
    """

    # -------------------- 步骤1：列出I2C设备 --------------------
    print("\n" + "=" * 60)
    print("可用I2C控制器:")
    print("=" * 60)

    # os.system() 执行shell命令
    # ls /dev/i2c* 列出所有I2C设备
    os.system('ls /dev/i2c*')

    print("=" * 60)

    # -------------------- 步骤2：获取用户输入 --------------------
    # input() 是Python的输入函数
    # 程序会暂停在这里，等待用户输入

    # 获取I2C总线号
    bus = input("请输入I2C总线号 (例如: 0, 1, 5): ")
    print(f"你选择了总线: i2c-{bus}")

    # 扫描总线上的设备
    print("\n扫描I2C总线上的设备...")
    os.system('i2cdetect -y -r ' + bus)

    # -------------------- 步骤3：获取设备地址 --------------------
    device = input("\n请输入要测试的设备地址(十六进制，例如: 0x51): ")
    print(f"你选择了设备地址: {device}")

    # -------------------- 步骤4：打开设备 --------------------
    print(f"\n正在打开I2C设备 {device} on 总线 {bus}...")

    try:
        # 创建I2C对象
        # I2C(地址, 总线号)
        # 注意：地址需要去掉0x前缀，因为i2cdev库用十进制
        addr = int(device, 16)  # 十六进制字符串转整数
        i2c = I2C(addr, int(bus))

        print(f"I2C设备已打开!")
        print(f"设备地址: hex=0x{addr:02X}, dec={addr}")

        # -------------------- 步骤5：读取数据 --------------------
        print("\n正在读取1字节数据...")
        value = i2c.read(1)  # 读取1个字节
        print(f"读取到的数据: {value}")

        # -------------------- 步骤6：写回数据 --------------------
        print("\n正在写回数据...")
        i2c.write(value)  # 把读到的数据写回去
        print("写入完成!")

        # -------------------- 步骤7：关闭设备 --------------------
        i2c.close()
        print("I2C设备已关闭")

    except Exception as e:
        print(f"操作失败: {e}")
        print("可能的原因:")
        print("  1. 设备地址不正确")
        print("  2. 设备未连接或损坏")
        print("  3. I2C总线号不正确")
        print("  4. 设备正被其他程序占用")

# ***************************************************************************************************
# 第四部分：自动扫描函数
# ***************************************************************************************************

def scan_all_i2c_buses():
    """
    scan_all_i2c_buses - 扫描所有I2C总线

    这是一个自动扫描函数
    遍历所有I2C总线，找出所有在线的设备
    """

    print("\n" + "=" * 60)
    print("自动扫描所有I2C总线")
    print("=" * 60)

    # 常见的I2C总线号
    common_buses = [0, 1, 5, 7]

    for bus in common_buses:
        print(f"\n扫描总线 i2c-{bus}...")

        try:
            # i2cdetect -y -r bus 是Linux下扫描I2C设备的命令
            # -y: 不需要确认
            # -r: 使用SMBus read byte命令
            result = os.popen(f'i2cdetect -y -r {bus}').read()
            print(result)

        except Exception as e:
            print(f"  总线 {bus} 扫描失败: {e}")

# ***************************************************************************************************
# 第五部分：主函数
# ***************************************************************************************************

def main():
    """
    main - 主函数
    """

    print("=" * 60)
    print("I2C通信测试程序")
    print("=" * 60)
    print("这个程序帮助你测试I2C设备")
    print("=" * 60)

    # 信号处理
    signal.signal(signal.SIGINT, signal_handler)

    # -------------------- 选择模式 --------------------
    print("\n请选择模式:")
    print("  1. 自动扫描所有I2C总线")
    print("  2. 手动指定I2C总线和设备")

    mode = input("\n请输入选项 (1 或 2): ")

    if mode == "1":
        scan_all_i2c_buses()
    else:
        i2cdevTest()

    # -------------------- 循环测试 --------------------
    print("\n" + "=" * 60)
    print("是否继续测试其他设备?")
    print("=" * 60)

    while True:
        choice = input("按回车继续测试，输入 q 退出: ")
        if choice.lower() == 'q':
            break
        i2cdevTest()

# ***************************************************************************************************
# 第六部分：程序入口
# ***************************************************************************************************

if __name__ == '__main__':
    main()

