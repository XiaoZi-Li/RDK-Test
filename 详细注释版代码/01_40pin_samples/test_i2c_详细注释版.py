# 1. I2C通信原理
#
#    I2C只用两根线：
#    ┌─────────────────────────────────────────────────────────────────┐
#    │                                                                 │
#    │   主设备                    从设备1        从设备2        从设备3  │
#    │      │                        │              │              │     │
#    │      │                        │              │              │     │
#    │   ───┴─── SCL (时钟线) ──────────────────────────────        │
#    │   ───┴─── SDA (数据线)  ─────┴──────────┴──┴────        │
#    │                                                                 │
#    │   SCL: 主设备产生时钟，通信速度由主设备控制                       │
#    │   SDA: 数据线，双向传输                                        │
#    │                                                                 │
#    └─────────────────────────────────────────────────────────────────┘
#
#    通信过程：
#    ┌─────────────────────────────────────────────────────────────────┐
#    │                                                                 │
#    │  1. 主设备发送START信号（SDA从高变低，SCL高）                    │
#    │                                                                 │
#    │  2. 主设备发送从设备地址(7位) + 读/写位                          │
#    │     例如: 0x51 + 0 = 写, 0x51 + 1 = 读                         │
#    │                                                                 │
#    │  3. 从设备发送ACK信号（SDA拉低）                                │
#    │                                                                 │
#    │  4. 主设备发送数据（写）或接收数据（读）                          │
#    │     每传输1字节，从设备都要ACK                                   │
#    │                                                                 │
#    │  5. 主设备发送STOP信号（SCL高，SDA从低变高）                    │
#    │                                                                 │
#    └─────────────────────────────────────────────────────────────────┘
#
# 2. I2C地址
#
#    每个I2C设备都有唯一的地址（7位或10位）
#    常见设备的默认地址：
#    ┌─────────────────────────────────────────────────────────────────┐
#    │  设备                │  常见地址 (7位)  │  备注                   │
#    ├──────────────────────┼──────────────────┼─────────────────────────┤
#    │  MPU6050 (陀螺仪)    │  0x68, 0x69    │  AD0引脚可改地址        │
#    │  BMP180 (气压)      │  0x77           │                        │
#    │  SSD1306 (OLED)     │  0x3C           │                        │
#    │  PCF8591 (ADC)      │  0x48           │                        │
#    │  AT24C256 (EEPROM)  │  0x50-0x57      │                        │
#    │  PCA9685 (PWM)      │  0x40           │                        │
#    │  ADS1115 (ADC)      │  0x48-0x4B      │  A0-A2引脚可改地址     │
#    └─────────────────────────────────────────────────────────────────┘
#
#    注意：地址通常是7位
#    实际传输时，会左移1位，然后加1位读写位
#    例如：0x68 -> 0xD0(写) 或 0xD1(读)
#
# 3. I2C vs SPI 对比
#
#    ┌────────────────┬─────────────┬─────────────┐
#    │ 特性           │ I2C         │ SPI         │
#    ├────────────────┼─────────────┼─────────────┤
#    │ 线数           │ 2根         │ 4根+        │
#    │ 速度           │ 较慢(400kHz)│ 更快(几十MHz)│
#    │ 设备数量       │ 多(总线上)  │ 每个独立     │
#    │ 地址           │ 需要地址     │ 需要片选    │
#    │ 全双工         │ 半双工       │ 全双工      │
#    └────────────────┴─────────────┴─────────────┘
