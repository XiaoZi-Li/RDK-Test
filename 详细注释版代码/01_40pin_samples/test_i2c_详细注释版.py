# │  什么是I2C？                                                                │
# │  I2C = Inter-Integrated Circuit (集成电路间总线)                             │
# │  是一种串行通信协议，只需要两根线就能通信：                                      │
# │  - SCL: 时钟线（Clock）                                                    │
# │  - SDA: 数据线（Data）                                                     │
# │                                                                             │
# │  I2C的特点：                                                               │
# │  - 只用2根线就能连接多个设备（总线型）                                        │
# │  - 每个设备有唯一的地址（7位或10位）                                         │
# │  - 主设备控制通信，从设备被动响应                                            │
# │                                                                             │
# │  常见I2C设备：                                                             │
# │  - 陀螺仪/加速度计（IMU）                                                  │
