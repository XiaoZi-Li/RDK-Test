#
# 1. 串口通信原理
#
#    串口是异步串行通信协议：
#    ┌─────────────────────────────────────────────────────────────────┐
#    │                                                                 │
#    │  空闲时: TX/RX 都保持高电平 (MARK状态)                         │
#    │                                                                 │
#    │  发送1字节的时序:                                              │
#    │                                                                 │
#    │  ┌───┐       ┌───┐                                       │
#    │  │起 ││数据位│ │停│                                      │
#    │  │位 ││0 1 2 │ │位│                                      │
#    │  └───┘│3 4 5 │ └───┘                                      │
#    │        │6 7   │                                             │
#    │  ──────┘       └───────                                    │
#    │  0         1                    1(停止位)                    │
#    │                                                                 │
#    │  空闲 → 起始位(0) → 数据位(5-8位) → 校验位(可选) → 停止位(1) │
#    │                                                                 │
#    └─────────────────────────────────────────────────────────────────┘
#
#    波特率和传输时间：
#    - 9600 波特率：每bit约104微秒，1字节约1.04毫秒
#    - 115200波特率：每bit约8.7微秒，1字节约87微秒
#
# 2. 接线方法
#
#    ┌─────────────────────────────────────────────────────────────────┐
#    │                                                                 │
#    │   开发板                    外部设备                            │
#    │      │                          │                                │
#    │      │─── TX (发送) ───────────┼─── RX (接收)                  │
#    │      │                          │                                │
#    │      │─── RX (接收) ───────────┼─── TX (发送)                  │
#    │      │                          │                                │
#    │      │─── GND (地线) ──────────┼─── GND                        │
#    │      │                          │                                │
#    │   (如果有)                      │                                │
#    │      │─── 3.3V/5V ────────────┼─── (供电, 如果需要)            │
#    │                                                                 │
#    │   注意：TX接RX，RX接TX，是交叉连接！                            │
#    │                                                                 │
#    └─────────────────────────────────────────────────────────────────┘
#
# 3. 常用波特率
#
#    ┌─────────────────────────────────────────────────────────────────┐
#    │  波特率     │  适用场景              │  说明                    │
#    ├─────────────┼────────────────────────┼─────────────────────────┤
#    │  9600      │  GPS, 某些模块         │  慢速，但可靠            │
#    │  19200     │  工业设备               │                         │
#    │  38400     │  工业设备               │                         │
#    │  57600     │  中速设备               │                         │
#    │  115200    │  大多数模块             │  最常用！                │
#    │  460800    │  高速模块               │                         │
#    │  921600    │  高速数据传输           │                         │
#    └─────────────────────────────────────────────────────────────────┘
#
# 4. TTL vs RS232 vs RS485
#
#    ┌────────────┬──────────────┬──────────────┐
#    │ 类型        │ 电压         │ 距离         │
#    ├────────────┼──────────────┼──────────────┤
#    │ TTL        │ 0-3.3V/5V   │ <1米        │
#    │ RS232      │ ±15V        │ ~15米       │
#    │ RS485      │ ±5V差分     │ ~1200米     │
#    └────────────┴──────────────┴──────────────┘
