# ***************************************************************************************************
# 第三部分：串口测试函数
# ***************************************************************************************************

def serialTest():
    """
    serialTest - 串口测试主函数

    测试流程：
    1. 列出所有可用的串口设备
    2. 让用户选择要测试的串口
    3. 选择波特率
    4. 打开串口
    5. 循环发送和接收数据
    """

    # -------------------- 步骤1：列出可用串口 --------------------
    print("\n" + "=" * 60)
    print("可用的串口设备:")
    print("=" * 60)

    # serial.tools.list_ports.comports() 返回所有可用串口列表
    ports = list(serial.tools.list_ports.comports())

    if len(ports) == 0:
        print("没有找到可用的串口设备！")
        print("请检查:")
        print("  1. 设备是否已连接")
        print("  2. 驱动是否已安装")
        print("  3. 设备是否被其他程序占用")
        return None

    # 打印每个串口的信息
    for i, port in enumerate(ports):
        # port对象有三个属性：
        # - device: 设备名，如 /dev/ttyUSB0 或 COM3
        # - name: 名称
        # - description: 描述
        print(f"  {i+1}. {port.device}")
        print(f"     名称: {port.name}")
        print(f"     描述: {port.description}")
        print()

    print("=" * 60)

    # -------------------- 步骤2：选择串口 --------------------
    # 让用户输入要使用的串口设备名
    uart_dev = input("请输入要测试的串口设备名 (例如: /dev/ttyUSB0 或 COM3): ")

    # 去除首尾空格
    uart_dev = uart_dev.strip()

    # -------------------- 步骤3：选择波特率 --------------------
    print("\n支持的波特率:")
    print("  9600   - 慢速设备, GPS, 某些模块")
    print("  19200  - 工业设备")
    print("  38400  - 工业设备")
    print("  57600  - 中速设备")
    print("  115200 - 最常用！大多数模块的默认波特率")
    print("  921600 - 高速数据传输")

    baudrate = input("\n请输入波特率 (默认115200): ")

    # 如果直接回车，使用默认115200
    if baudrate.strip() == "":
        baudrate = "115200"

    # 转换为整数
    try:
        baudrate = int(baudrate)
    except ValueError:
        print("波特率无效，使用默认115200")
        baudrate = 115200

    # -------------------- 步骤4：打开串口 --------------------
    print(f"\n正在打开串口 {uart_dev} @ {baudrate} bps...")

    try:
        # serial.Serial() 创建串口对象
        #
        # 常用参数：
        # - port: 设备名
        # - baudrate: 波特率
        # - bytesize: 数据位 (serial.EIGHTBITS等)
        # - stopbits: 停止位 (serial.STOPBITS_ONE等)
        # - parity: 校验位 (serial.PARITY_NONE等)
        # - timeout: 读取超时(秒)
        #
        ser = serial.Serial(
            port=uart_dev,
            baudrate=baudrate,
            bytesize=serial.EIGHTBITS,     # 8位数据位
            stopbits=serial.STOPBITS_ONE, # 1位停止位
            parity=serial.PARITY_NONE,    # 无校验
            timeout=1                      # 1秒超时
        )

        print("串口已打开!")
        print(f"  设备: {ser.port}")
        print(f"  波特率: {ser.baudrate}")
        print(f"  数据位: {ser.bytesize}")
        print(f"  停止位: {ser.stopbits}")
        print(f"  校验: {ser.parity}")
        print(f"  超时: {ser.timeout}s")

    except serial.SerialException as e:
        print(f"打开串口失败: {e}")
        print("可能的原因:")
        print("  1. 设备不存在")
        print("  2. 设备正被其他程序占用")
        print("  3. 权限不足")
        return None

    # -------------------- 步骤5：发送接收测试 --------------------
    print("\n" + "=" * 60)
    print("串口测试模式")
    print("=" * 60)
    print("发送: AA55 (十六进制测试数据)")
    print("=" * 60)

    try:
        # 测试数据
        test_data = "AA55"

        while True:
            # -------- 发送数据 --------
            # encode('UTF-8') 将字符串转换为字节
            # Python3串口通信使用字节串，不是字符串
            write_num = ser.write(test_data.encode('UTF-8'))
            print(f"发送 ({write_num}字节): {test_data}")

            # -------- 接收数据 --------
            # read() 读取数据
            # 参数是字节数，读取指定数量的字节
            # 如果超时则返回空字节串
            received_data = ser.read(write_num)

            if len(received_data) > 0:
                # 成功接收到数据
                # decode('UTF-8') 将字节转换为字符串
                received_str = received_data.decode('UTF-8', errors='replace')
                print(f"接收 ({len(received_data)}字节): {received_str}")

                # 检查是否一致
                if received_str == test_data:
                    print("✓ 数据一致，通信正常!")
                else:
                    print("✗ 数据不一致，可能有错误")
            else:
                print("接收超时（无数据返回）")
                print("提示: 确保TX和RX正确连接，且对方设备在正常工作")

            # -------- 延时 --------
            time.sleep(1)

    except KeyboardInterrupt:
        print("\n用户中断")

    finally:
        # -------- 关闭串口 --------
        if ser.is_open:
            ser.close()
            print("\n串口已关闭")

# ***************************************************************************************************
# 第四部分：直接测试函数（无需交互）
# ***************************************************************************************************

def quick_test(port="/dev/ttyUSB0", baudrate=115200):
    """
    quick_test - 快速测试函数

    参数:
        port: 串口设备名
        baudrate: 波特率

    直接打开串口并测试，不需要交互输入
    """

    print(f"快速测试: {port} @ {baudrate}")

    try:
        # 打开串口
        ser = serial.Serial(port, baudrate, timeout=1)

        # 发送测试数据
        test_bytes = bytes.fromhex("AA55")
        ser.write(test_bytes)
        print(f"发送: {test_bytes.hex()}")

        # 接收
        received = ser.read(2)
        print(f"接收: {received.hex()}")

        ser.close()

        return True

    except Exception as e:
        print(f"测试失败: {e}")
        return False

