#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
usb_camera_snap.py - USB摄像头图像捕获示例
================================================================================

【程序功能】
本程序演示如何从USB摄像头捕获单帧图像并保存到文件。
这是一个基础的摄像头使用示例，展示了摄像头初始化、参数配置和图像捕获的完整流程。

【硬件要求】
- USB摄像头（支持V4L2协议）
- 连接后可通过 /dev/videoX 设备文件访问

【功能特点】
1. 自动检测系统中第一个可用的USB摄像头
2. 支持通过命令行参数指定摄像头设备
3. 配置摄像头输出格式为MJPEG，分辨率1920x1080
4. 捕获单帧图像并保存为JPEG格式

【运行方式】
# 自动检测摄像头
python3 usb_camera_snap.py

# 指定摄像头设备
python3 usb_camera_snap.py /dev/video1

【输出文件】
- 当前目录生成 img.jpg 文件

================================================================================
"""

import os
import sys
import cv2

def is_usb_camera(device):
    """
    检测指定设备是否为可用的USB摄像头

    【参数】
        device: 设备路径，如 /dev/video0

    【返回值】
        True: 是可用的摄像头
        False: 不是摄像头或无法打开

    【检测方法】
        尝试打开设备并检查是否能成功初始化
        使用cv2.VideoCapture检查设备是否可用
    """
    try:
        cap = cv2.VideoCapture(device)
        if not cap.isOpened():
            return False
        cap.release()
        return True
    except Exception:
        return False

def find_first_usb_camera():
    """
    自动查找系统中第一个可用的USB摄像头

    【返回值】
        摄像头设备路径（如 /dev/video0）
        如果没有找到返回 None

    【搜索策略】
        遍历 /dev 目录下所有 video* 开头的设备
        对每个设备调用 is_usb_camera() 检测是否可用
    """
    video_devices = [os.path.join('/dev', dev) for dev in os.listdir('/dev') if dev.startswith('video')]
    for dev in video_devices:
        if is_usb_camera(dev):
            return dev
    return None

# ================================================================================
# 主程序入口
# ================================================================================

if __name__ == '__main__':
    # ==========================================================================
    # 第1步：确定使用的摄像头设备
    # ==========================================================================
    # 如果命令行提供了设备路径，使用指定的设备
    # 否则自动搜索第一个可用的USB摄像头
    if len(sys.argv) > 1:
        video_device = sys.argv[1]
    else:
        video_device = find_first_usb_camera()

    # ==========================================================================
    # 第2步：检查摄像头是否可用
    # ==========================================================================
    if video_device is None:
        print("No USB camera found.")
        sys.exit(-1)

    print(f"Opening video device: {video_device}")

    # ==========================================================================
    # 第3步：打开摄像头
    # ==========================================================================
    cap = cv2.VideoCapture(video_device)

    if not cap.isOpened():
        print(f"Failed to open video device: {video_device}")
        sys.exit(-1)

    print("Open USB camera successfully")

    # ==========================================================================
    # 第4步：配置摄像头参数
    # ==========================================================================
    # 设置输出图像格式为 MJPEG
    # MJPEG：Motion JPEG，将视频帧压缩为JPEG图像序列
    # 优点：画质好，解码简单
    # 缺点：压缩比较低，带宽占用大
    codec = cv2.VideoWriter_fourcc('M', 'J', 'P', 'G')
    cap.set(cv2.CAP_PROP_FOURCC, codec)

    # 设置帧率：30 FPS
    cap.set(cv2.CAP_PROP_FPS, 30)

    # 设置分辨率：1920 x 1080（全高清）
    cap.set(cv2.CAP_PROP_FRAME_WIDTH, 1920)
    cap.set(cv2.CAP_PROP_FRAME_HEIGHT, 1080)

    # ==========================================================================
    # 第5步：捕获单帧图像
    # ==========================================================================
    ret, frame = cap.read()

    # ==========================================================================
    # 第6步：检查捕获结果
    # ==========================================================================
    if not ret or frame is None:
        print("Failed to get image from USB camera")
        cap.release()
        sys.exit(-1)

    # ==========================================================================
    # 第7步：保存图像到文件
    # ==========================================================================
    cv2.imwrite("img.jpg", frame)
    print("Image saved as img.jpg")

    # ==========================================================================
    # 第8步：释放摄像头资源
    # ==========================================================================
    cap.release()

# ================================================================================
# 【V4L2摄像头参数说明】
# ================================================================================
# V4L2 (Video4Linux2) 是Linux内核的视频设备驱动框架
#
# 常用参数：
# | 参数                    | 说明                      | 常用值        |
# |-------------------------|--------------------------|---------------|
# | CAP_PROP_FOURCC        | 视频编码格式              | MJPG/YUYV    |
# | CAP_PROP_FPS           | 帧率                     | 15/30/60     |
# | CAP_PROP_FRAME_WIDTH   | 图像宽度                 | 640/1280/1920|
# | CAP_PROP_FRAME_HEIGHT  | 图像高度                 | 480/720/1080 |
# | CAP_PROP_BUFFERSIZE    | 缓冲区大小               | 1-10         |
#
# 支持的格式：
# - MJPEG：Motion JPEG，压缩率高，画质好
# - YUYV：未压缩格式，YUV422格式
# - H264：需要摄像头支持硬件编码
#
# 【摄像头分辨率支持查询】
# 可以使用v4l2-ctl命令查看：
# v4l2-ctl -d /dev/video0 --list-formats-ext
